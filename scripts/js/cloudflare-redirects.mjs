import { stat } from 'node:fs/promises'
import path from 'node:path'

/** @typedef {{ from: string, to: string, status: number }} Redirect */

const dynamicPath = /\*|:[A-Za-z]\w*/u
const statuses = new Set([200, 301, 302, 303, 307, 308])

/**
 * Emit the supported Pages redirect format with exact paths before patterns.
 * Cloudflare counts every rule after the first pattern against the dynamic limit.
 * https://developers.cloudflare.com/pages/configuration/redirects/
 * @param {string} source
 * @returns {{ output: string, rules: Redirect[], staticCount: number, dynamicCount: number }}
 */
export const prepareCloudflareRedirects = source => {
  /** @type {Redirect[]} */
  const staticRules = []
  /** @type {Redirect[]} */
  const dynamicRules = []
  const seen = new Set()

  for (const rawLine of source.split(/\r?\n/u)) {
    const line = rawLine.trim()

    if (!line || line.startsWith('#')) continue

    if (line.length > 1000) throw new Error('Redirect line exceeds the Cloudflare Pages 1000-character limit')

    const [from, to, statusText = '302', extra] = line.split(/\s+/u)
    const status = Number(statusText)

    if (!from || !to || extra || !statuses.has(status)) throw new Error(`Invalid redirect rule: ${line}`)

    if (!from.startsWith('/') || from.startsWith('//') || /[?#\\]/u.test(from)) {
      throw new Error(`Redirect source must be a relative path without a query or fragment: ${from}`)
    }

    if (!(to.startsWith('/') && !to.startsWith('//')) && !to.startsWith('https://')) {
      throw new Error(`Redirect destination must be a relative path or HTTPS URL: ${to}`)
    }

    if (status === 200 && to.startsWith('https://')) throw new Error(`Proxy destination must be relative: ${to}`)

    if (from === to) throw new Error(`Redirect points to itself: ${from}`)

    if (seen.has(from)) throw new Error(`Duplicate redirect source: ${from}`)

    seen.add(from)

    const rules = dynamicPath.test(from) ? dynamicRules : staticRules

    rules.push({ from, to, status })
  }

  if (staticRules.length > 2000) throw new Error(`Cloudflare Pages supports 2000 static redirects; found ${staticRules.length}`)

  if (dynamicRules.length > 100) throw new Error(`Cloudflare Pages supports 100 dynamic redirects; found ${dynamicRules.length}`)

  const render = (/** @type {Redirect[]} */ rules) => rules.map(({ from, to, status }) => `${from}  ${to}  ${status}`)

  return {
    output: [
      '# Generated by scripts/js/generate-cloudflare-redirects.mjs. Do not edit.',
      '# Exact paths must precede wildcard and placeholder rules.',
      ...render(staticRules),
      '',
      '# Dynamic rules (preserve their relative order)',
      ...render(dynamicRules),
      ''
    ].join('\n'),
    rules: [...staticRules, ...dynamicRules],
    staticCount: staticRules.length,
    dynamicCount: dynamicRules.length
  }
}

/**
 * Validate concrete local targets, including rules not linked from any page.
 * @param {Redirect[]} rules
 * @param {string} directory
 */
export const validateRedirectDestinations = async (rules, directory) => {
  for (const to of new Set(rules.map(rule => rule.to))) {
    const url = new URL(to, 'https://santi020k.com')

    if (url.origin !== 'https://santi020k.com' || dynamicPath.test(url.pathname)) continue

    const pathname = url.pathname
    let decoded

    try {
      decoded = decodeURIComponent(pathname).replace(/^\/+/, '')
    } catch (cause) {
      throw new Error(`Redirect destination has invalid URL encoding: ${to}`, { cause })
    }

    const file = path.resolve(directory, pathname.endsWith('/') ? `${decoded}index.html` : decoded)
    const relative = path.relative(directory, file)

    if (relative === '..' || relative.startsWith(`..${path.sep}`) || path.isAbsolute(relative)) {
      throw new Error(`Redirect destination resolves outside the build: ${to}`)
    }

    try {
      if (!(await stat(file)).isFile()) throw new Error('Expected a built file')
    } catch (cause) {
      throw new Error(`Redirect destination is missing from the build: ${to}`, { cause })
    }
  }
}
